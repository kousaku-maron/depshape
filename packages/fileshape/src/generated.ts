/*
 * Whether a changed file is generated (lock files, build output, code generators), so the screen folds
 * it at first: by its path, then by the first lines of the file when the diff shows them.
 */

import type { DiffFile } from "./types.js";

const EXACT_FILENAMES = new Set([
  "package-lock.json",
  "pnpm-lock.yaml",
  "yarn.lock",
  "Gemfile.lock",
  "Pipfile.lock",
  "composer.lock",
  "Cargo.lock",
  "poetry.lock",
  "go.sum",
  "pubspec.lock",
  "flake.lock",
  "Package.resolved",
  "packages.lock.json",
  ".terraform.lock.hcl",
  "bun.lockb",
  "bun.lock",
  "gradle.lockfile",
  "uv.lock",
  "pdm.lock",
]);

const FILENAME_SUFFIXES = [
  ".min.js",
  ".min.css",
  ".bundle.js",
  ".bundle.css",
  "-min.js",
  ".map",
  ".pb.go",
  ".pb.rb",
  ".pb.py",
  ".pb.js",
  ".pb.cc",
  ".pb.h",
  "_pb2.py",
  ".pb2.py",
  ".grpc.pb.go",
  "_string.go",
  ".graphql.ts",
  ".graphql.js",
  ".g.dart",
  ".freezed.dart",
  ".g.cs",
  ".designer.cs",
];

const ROOT_PREFIXES = ["vendor/", "node_modules/", "dist/", "build/", "out/"];
const PATH_SEGMENTS = ["/generated/", "/gen/", "/__generated__/"];

/** "x.generated.ts", "x.gen.go" */
const GENERATED_EXT = /\.(generated|gen)\.\w+$/;

const HEADER_PATTERNS = [
  /@generated\b/,
  /\bDO NOT EDIT\b/i,
  /\bDO NOT MODIFY\b/i,
  /\bAUTO[- ]?GENERATED\b/i,
  /\bTHIS FILE IS GENERATED\b/i,
  /\bGENERATED CODE\b/i,
  /\bMACHINE GENERATED\b/i,
  /This file was generated/i,
  /This is a generated file/i,
  /<auto-generated\s*\/?>/i,
  /^\/\/ Code generated .* DO NOT EDIT\.$/m,
];

export function generatedByPath(path: string): boolean {
  const name = path.split("/").pop() ?? "";
  return (
    EXACT_FILENAMES.has(name) ||
    FILENAME_SUFFIXES.some((s) => name.endsWith(s)) ||
    GENERATED_EXT.test(name) ||
    (name.startsWith("mock_") && name.endsWith(".go")) ||
    ((path.startsWith("mocks/") || path.includes("/mocks/")) && name.endsWith(".go")) ||
    ROOT_PREFIXES.some((p) => path.startsWith(p)) ||
    PATH_SEGMENTS.some((s) => path.includes(s))
  );
}

/** The first lines of the file on the target side, when the first chunk starts there */
function headerLines(file: DiffFile): string[] {
  const first = file.chunks[0];
  if (!first || first.newStart > 1 || file.status === "removed") return [];
  return first.lines
    .filter((l) => l.type !== "delete")
    .slice(0, 20)
    .map((l) => l.content);
}

export function isGenerated(file: DiffFile): boolean {
  if (generatedByPath(file.path)) return true;
  // documentation often quotes generated headers as examples
  if (/\.(md|markdown|mdx)$/i.test(file.path)) return false;
  const header = headerLines(file).join("\n");
  return header !== "" && HEADER_PATTERNS.some((p) => p.test(header));
}
