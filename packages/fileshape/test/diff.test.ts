import { describe, expect, it } from "vitest";
import { addedFile, decodeGitPath, parseUnifiedDiff } from "../src/diff.js";
import { generatedByPath, isGenerated } from "../src/generated.js";

describe("parseUnifiedDiff", () => {
  it("reads hunks, line numbers and the section after @@", () => {
    const text = [
      "diff --git a/x.ts b/x.ts",
      "index 1111111..2222222 100644",
      "--- a/x.ts",
      "+++ b/x.ts",
      "@@ -3,4 +3,4 @@ function f() {",
      " a",
      "-b",
      "+B",
      "--- not a header inside a hunk",
      " c",
      "\\ No newline at end of file",
      "",
    ].join("\n");
    const [f] = parseUnifiedDiff(text);
    expect(f).toMatchObject({ path: "x.ts", status: "modified", additions: 1, deletions: 2 });
    expect(f.chunks[0]).toMatchObject({ section: "function f() {", oldStart: 3, oldLines: 4, newStart: 3, newLines: 4 });
    expect(f.chunks[0].lines).toEqual([
      { type: "normal", content: "a", oldLine: 3, newLine: 3 },
      { type: "delete", content: "b", oldLine: 4 },
      { type: "add", content: "B", newLine: 4 },
      { type: "delete", content: "-- not a header inside a hunk", oldLine: 5 },
      { type: "normal", content: "c", oldLine: 6, newLine: 5 },
    ]);
  });

  it("takes paths from the header when there are no ---/+++ lines", () => {
    const text = ["diff --git a/dir with space/x.png b/dir with space/x.png", "index 1..2 100644", "Binary files a/dir with space/x.png and b/dir with space/x.png differ", ""].join("\n");
    expect(parseUnifiedDiff(text)).toEqual([{ path: "dir with space/x.png", status: "modified", additions: 0, deletions: 0, chunks: [], binary: true }]);
  });

  it("reads several files, added and removed ones too", () => {
    const text = [
      "diff --git a/new.txt b/new.txt",
      "new file mode 100644",
      "--- /dev/null",
      "+++ b/new.txt",
      "@@ -0,0 +1 @@",
      "+hi",
      "diff --git a/old.txt b/old.txt",
      "deleted file mode 100644",
      "--- a/old.txt",
      "+++ /dev/null",
      "@@ -1 +0,0 @@",
      "-bye",
      "",
    ].join("\n");
    const files = parseUnifiedDiff(text);
    expect(files.map((f) => [f.path, f.status, f.additions, f.deletions])).toEqual([
      ["new.txt", "added", 1, 0],
      ["old.txt", "removed", 0, 1],
    ]);
  });
});

describe("decodeGitPath", () => {
  it("decodes quoted paths with octal bytes and escapes", () => {
    expect(decodeGitPath('"a/\\346\\227\\245.txt"')).toBe("日.txt");
    expect(decodeGitPath('"b/tab\\there"')).toBe("tab\there");
    expect(decodeGitPath("/dev/null")).toBeUndefined();
    expect(decodeGitPath("src/a.ts", false)).toBe("src/a.ts");
  });
});

describe("addedFile", () => {
  it("makes one chunk of added lines, and none for a binary file", () => {
    expect(addedFile("a.txt", "x\ny\n").chunks[0].lines.map((l) => [l.type, l.content, l.newLine])).toEqual([
      ["add", "x", 1],
      ["add", "y", 2],
    ]);
    expect(addedFile("b.bin", "a\0b")).toMatchObject({ binary: true, chunks: [] });
  });
});

describe("generated files", () => {
  it("knows lock files, build output and generated names", () => {
    for (const p of ["pnpm-lock.yaml", "web/package-lock.json", "go.sum", "dist/app.js", "x/__generated__/q.ts", "api.pb.go", "schema.generated.ts", "app.min.js", "mock_repo.go"]) expect(generatedByPath(p), p).toBe(true);
    for (const p of ["go.mod", "src/app.ts", "README.md", "src/distance.ts"]) expect(generatedByPath(p), p).toBe(false);
  });

  it("reads the first lines of the file when the diff shows them", () => {
    const file = addedFile("gen/x_types.ts", "// Code generated by tool. DO NOT EDIT.\nexport {};\n");
    file.path = "src/x_types.ts";
    expect(isGenerated(file)).toBe(true);
    const doc = addedFile("docs/how.md", "Put `// DO NOT EDIT` at the top\n");
    expect(isGenerated(doc)).toBe(false);
  });
});
